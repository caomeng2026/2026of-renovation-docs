changed_text = 0
for p in doc.paragraphs:
    for old, new in text_repl:
        if old in p.text:
            # 替换所有 run 中的文本（金额可能跨 run，需逐段合并处理）
            for run in p.runs:
                if old in run.text:
                    run.text = run.text.replace(old, new)
                    changed_text += 1
            # 处理跨 run 的情况：直接重写段落第一个 run，其余清空
            full = p.text
            if old in full and not any(old in r.text for r in p.runs):
                # 跨 run，合并到第一个 run
                if p.runs:
                    p.runs[0].text = full.replace(old, new)
                    for r in p.runs[1:]:
                        r.text = ''
                    changed_text += 1

